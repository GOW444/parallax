"""Write metrics and inferences to results/ so the report never contains hand-typed numbers.

Why: the rubric checks correctness of inferences. If every number lives in a results
file and the report reads from there, a re-run can never leave a stale number behind.
"""

import json
import re
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from src import config


def _to_jsonable(value: Any) -> Any:
    """Recursively convert numpy/pandas values into plain JSON-safe Python types.

    NaN/inf become None: JSON has no NaN, and json.dump would otherwise write the
    invalid token `NaN` (np.float64 is a float subclass, so it skips any `default=` hook).
    """
    if isinstance(value, dict):
        return {str(k): _to_jsonable(v) for k, v in value.items()}
    if isinstance(value, list | tuple | np.ndarray | pd.Series):
        return [_to_jsonable(v) for v in list(value)]
    if isinstance(value, bool | np.bool_):
        return bool(value)
    if isinstance(value, int | np.integer):
        return int(value)
    if isinstance(value, float | np.floating):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, pd.Timestamp):
        return value.isoformat()
    if value is None or isinstance(value, str):
        return value
    raise TypeError(f"cannot serialise {type(value).__name__}")


def save_metrics(name: str, data: dict, results_dir: Path = config.RESULTS) -> Path:
    """Save a dict of metrics as results/<name>.json (overwrites: re-runs stay in sync)."""
    if not re.fullmatch(r"[A-Za-z0-9_]+", name):
        raise ValueError(f"metric name must be alphanumeric/underscore, got {name!r}")
    results_dir.mkdir(parents=True, exist_ok=True)
    path = results_dir / f"{name}.json"
    # allow_nan=False: fail loudly rather than ever write invalid JSON
    path.write_text(json.dumps(_to_jsonable(data), indent=2, allow_nan=False), encoding="utf-8")
    return path


def load_metrics(name: str, results_dir: Path = config.RESULTS) -> dict:
    """Read results/<name>.json back (used by the notebook narrative and the report)."""
    return json.loads((results_dir / f"{name}.json").read_text(encoding="utf-8"))


def write_notes(
    name: str, title: str, bullets: list[str], results_dir: Path = config.RESULTS
) -> Path:
    """Write a generated markdown note (results/<name>.md) from bullet strings.

    The bullets are built in the notebook from computed values, so the note can never
    disagree with the data.
    """
    lines = [f"# {title}", "", "_Generated by the notebook. Do not edit by hand._", ""]
    lines += [f"- {b}" for b in bullets]
    path = results_dir / f"{name}.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _inference_sort_key(inference_id: str) -> tuple:
    """Sort IDs naturally: I1-2 before I1-10, and iteration 1 before iteration 2."""
    return tuple(int(n) for n in re.findall(r"\d+", inference_id))


def log_inference(
    inference_id: str,
    statement: str,
    evidence: str,
    triggers_loop: bool,
    transformation: str = "",
    json_path: Path = config.INFERENCES_JSON,
    md_path: Path = config.INFERENCES_MD,
) -> None:
    """Insert or replace one inference and re-render the markdown log.

    `evidence` must name at least one figure (.png) or results file, so every
    inference stays traceable to an output.
    """
    if not re.fullmatch(r"I\d+-\d+", inference_id):
        raise ValueError(f"inference id must look like I1-3, got {inference_id!r}")
    if not re.search(r"\.(png|json|csv)", evidence):
        raise ValueError(f"{inference_id}: evidence must cite a figure or results file")
    if triggers_loop and not transformation.strip():
        raise ValueError(
            f"{inference_id}: an inference that triggers the loop needs a transformation"
        )

    entries = json.loads(json_path.read_text(encoding="utf-8")) if json_path.exists() else {}
    entries[inference_id] = {
        "statement": statement,
        "evidence": evidence,
        "triggers_loop": triggers_loop,
        "transformation": transformation,
    }
    entries = dict(sorted(entries.items(), key=lambda kv: _inference_sort_key(kv[0])))
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(entries, indent=2), encoding="utf-8")
    md_path.write_text(render_inferences_md(entries), encoding="utf-8")


def render_inferences_md(entries: dict) -> str:
    """Render the inference log as markdown (generated file: never edit it by hand)."""
    lines = [
        "# Inference log",
        "",
        "_Generated by `src/logbook.py` from `inferences.json`. Do not edit by hand._",
        "",
    ]
    for inference_id, e in entries.items():
        lines += [
            f"## {inference_id}",
            "",
            f"**Statement:** {e['statement']}",
            "",
            f"**Evidence:** {e['evidence']}",
            "",
            f"**Triggers feedback loop:** {'Yes' if e['triggers_loop'] else 'No'}",
        ]
        if e["transformation"]:
            lines += ["", f"**Transformation:** {e['transformation']}"]
        lines.append("")
    rows = loop_rows(entries)
    if rows:
        lines += [
            "## Feedback loop: inference -> transformation",
            "",
            "| Inference | Transformation | What changes | Output | Before/after figure |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {r['inference']} | {r['transformation']} | {r['what_changes']} | "
            f"{r['outputs']} | {r['figure']} |"
            for r in rows
        ]
        lines.append("")
    return "\n".join(lines)


def loop_rows(entries: dict, details: dict = config.LOOP_DETAILS) -> list[dict]:
    """One row per loop-triggering inference, from the log plus config.LOOP_DETAILS.

    Built from the same inference log as the markdown, so the CSV table and inferences.md
    can never disagree. An inference that triggers the loop without a LOOP_DETAILS entry
    falls back to its own transformation text.
    """
    rows = []
    for inference_id, e in entries.items():
        if not e["triggers_loop"]:
            continue
        d = details.get(inference_id, {})
        rows.append(
            {
                "inference": inference_id,
                "transformation": d.get("transformation", e["transformation"]),
                "what_changes": d.get("what_changes", ""),
                "outputs": d.get("outputs", ""),
                "figure": d.get("figure", ""),
                "evidence": e["evidence"],
            }
        )
    return rows


def write_loop_table(
    json_path: Path = config.INFERENCES_JSON,
    md_path: Path = config.INFERENCES_MD,
    csv_path: Path = config.RESULTS / "loop_transformations.csv",
) -> pd.DataFrame:
    """Write results/loop_transformations.csv and re-render inferences.md with the table."""
    entries = json.loads(json_path.read_text(encoding="utf-8"))
    table = pd.DataFrame(loop_rows(entries))
    table.to_csv(csv_path, index=False)
    md_path.write_text(render_inferences_md(entries), encoding="utf-8")
    return table


# ---------------------------------------------------------------------------- inference text
def format_p(p: float) -> str:
    """'< 0.001' for tiny p-values, otherwise '= 0.123' (for 'p {format_p(p)}')."""
    return "< 0.001" if p < 0.001 else f"= {p:.3f}"


def group_medians_text(block: dict, signed: bool = False, tested_only: bool = False) -> str:
    """'Hydro -205, Coal +185' from a stats.compare_groups() result (sign shown if signed)."""
    rows = block["by_group"]
    if tested_only:
        rows = [g for g in rows if g["group"] in block["groups_tested"]]
    fmt = "{:+.0f}" if signed else "{:.0f}"
    return ", ".join(f"{g['group']} {fmt.format(g['median'])}" for g in rows)


def join_words(items: list[str]) -> str:
    """['a', 'b', 'c'] -> 'a, b and c' (empty list -> 'none')."""
    if not items:
        return "none"
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def dominated_text(sources: list[str]) -> str:
    """['Hydro', 'Nuclear'] -> 'hydro- and nuclear-dominated' (hyphenated compound)."""
    words = [s.lower() + "-" for s in sources]
    words[-1] = words[-1] + "dominated"
    return join_words(words)


def significance_text(p: float, alpha: float = config.ALPHA) -> str:
    """'p = 0.379, not significant' / 'p < 0.001, significant' at the given alpha."""
    verdict = "significant" if p < alpha else "not significant"
    return f"p {format_p(p)}, {verdict}"


def groups_by_sign(block: dict) -> tuple[list[str], list[str]]:
    """Tested groups whose median is below 0 and above 0, in table order."""
    tested = [g for g in block["by_group"] if g["group"] in block["groups_tested"]]
    below = [g["group"] for g in tested if g["median"] < 0]
    above = [g["group"] for g in tested if g["median"] > 0]
    return below, above
